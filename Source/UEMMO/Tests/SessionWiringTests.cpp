	// Fixed simulated frame step (60 fps like the design frame clock). The
	// world is driven ONLY through real ticks; the session clock is never
	// injected by this suite.
	constexpr float M2_016_FrameSeconds = 1.0f / 60.0f;

	// The floor: top face exactly at z=0 so the Data/rooms.json spawn heights
	// (z=88) drop the enemies a short way onto the floor, like the arena maps.
	const FVector M2_016_FloorCenter(300.0, 0.0, -100.0);
	const FVector M2_016_FloorHalfExtent(2200.0, 1500.0, 100.0);

	// Player start far outside the activation volume; the trigger volume
	// covers x in [-250, 50] around (-100, 0, 88) (the production default
	// placement of L_CombatRoom01).
	const FVector M2_016_PlayerOutside(-800.0, 0.0, 120.0);
	const FVector M2_016_PlayerInside(-100.0, 0.0, 120.0);
	const FVector M2_016_TriggerLocation(-100.0, 0.0, 88.0);

	// The wave spawn locations of the trigger's default wave data (the
	// Data/rooms.json room_training_01 shape: wave 0 two, wave 1 three). The
	// suite pins these so the trigger's production defaults stay the catalog
	// shape; births must land at or near one of them.
	const FVector M2_016_Wave0Locations[2] = {
		FVector(300.0, 0.0, 88.0),
		FVector(450.0, -150.0, 88.0)
	};
	const FVector M2_016_Wave1Locations[3] = {
		FVector(600.0, 100.0, 88.0),
		FVector(750.0, -100.0, 88.0),
		FVector(0.0, 300.0, 88.0)
	};

	// Loose birth-location band (cm): a spawned capsule settles a few
	// centimetres onto the floor; the band still catches gross mis-spawns.
	constexpr double M2_016_BirthLocationBandCm = 300.0;

	// The spawn slot interval and the inter-wave gap (the M2-007/M2-008
	// production constants the character-clock pump rides on) plus the
	// assertion band around a 0.3 s slot observed on the real frame clock.
	constexpr double M2_016_SpawnSlotSeconds = 0.3;
	constexpr double M2_016_SlotBandLowSeconds = 0.2;
	constexpr double M2_016_SlotBandHighSeconds = 0.5;
	constexpr double M2_016_WaveGapSeconds = 1.0;

	// Enemy asset generated by Scripts/Editor/create_enemy_assets.py from
	// Data/enemies.json (the melee_grunt row).
	const TCHAR* M2_016_EnemyAssetPath =
		TEXT("/Game/UEMMO/Enemy/Definitions/DA_melee_grunt.DA_melee_grunt");

	// World-static blocking box (the M2-010/M2-014 floor builder shape).
	static AActor* M2_016_SpawnBoxActor(UWorld& World, const FVector& Center,
		const FVector& HalfExtent, const TCHAR* Name)
	{
		FActorSpawnParameters Params;
		AActor* Actor = World.SpawnActor<AActor>(AActor::StaticClass(), Center, FRotator::ZeroRotator, Params);
		if (Actor == nullptr)
		{
			return nullptr;
		}
		UBoxComponent* Box = NewObject<UBoxComponent>(Actor, Name);
		Actor->SetRootComponent(Box);
		Box->SetMobility(EComponentMobility::Movable);
		Box->SetBoxExtent(HalfExtent);
		Box->SetCollisionProfileName(UCollisionProfile::BlockAll_ProfileName);
		Box->RegisterComponent();
		Box->SetWorldLocation(Center);
		return Actor;
	}

	// Spawns the real prototype pawn above the floor and lets it settle with
	// real physics and no controller (the M2-010/M2-014 rig).
	static APrototypeCharacter* M2_016_SpawnPlayer(UWorld& World, const FVector& Location)
	{
		FActorSpawnParameters Params;
		APrototypeCharacter* Player = World.SpawnActor<APrototypeCharacter>(
			APrototypeCharacter::StaticClass(), Location, FRotator::ZeroRotator, Params);
		if (Player == nullptr)
		{
			return nullptr;
		}
		if (UCharacterMovementComponent* Movement = Player->GetCharacterMovement())
		{
			Movement->bRunPhysicsWithNoController = true;
			if (!Movement->IsActive())
			{
				Movement->Activate(/*bReset*/ true);
			}
			if (Movement->MovementMode == MOVE_None)
			{
				Movement->SetDefaultMovementMode();
			}
		}
		return Player;
	}

	// The in-loop scene: real world, real session, real trigger, real pawn,
	// real HUD - and NO test clock anywhere. All timing comes from the
	// world ticks through the production character-tick session injection.
	struct FM2_016_Scene
	{
		FTestWorldWrapper Wrapper;
		UWorld* World = nullptr;
		URoomSessionSubsystem* Session = nullptr;
		ARoomTrigger* Trigger = nullptr;
		APrototypeCharacter* Player = nullptr;
		APrototypeHUD* Hud = nullptr;

		// Session event counters (the assertions read these only).
		int32 StartedCount = 0;
		int32 EndedCount = 0;
		TArray<FRoomResult> EndedResults;
		int32 PlayerDiedCount = 0;

		// Spawn sampling: the world-clock time each newly seen enemy first
		// appeared at, and the enemies already killed (corpses never shadow a
		// fresh kill target).
		TArray<double> EnemySpawnTimes;
		TArray<TWeakObjectPtr<AActor>> KilledEnemies;

		bool Build(FAutomationTestBase& Test)
		{
			if (!Test.TestTrue(TEXT("the test world is created (engine FTestWorldWrapper precedent)"),
				Wrapper.CreateTestWorld(EWorldType::Game)))
			{
				return false;
			}
			World = Wrapper.GetTestWorld();
			if (!Test.TestNotNull(TEXT("the test world is available"), World))
			{
				return false;
			}
			if (!Test.TestTrue(TEXT("play begins in the test world (full actor initialization)"),
				Wrapper.BeginPlayInTestWorld()))
			{
				return false;
			}
			Session = World->GetSubsystem<URoomSessionSubsystem>();
			if (!Test.TestNotNull(TEXT("the room session subsystem exists in the test world"), Session))
			{
				return false;
			}
			Session->OnRunStarted().AddLambda([this]()
			{
				++StartedCount;
			});
			Session->OnRunEnded().AddLambda([this](const FRoomResult& Result)
			{
				++EndedCount;
				EndedResults.Add(Result);
			});

			if (M2_016_SpawnBoxActor(*World, M2_016_FloorCenter, M2_016_FloorHalfExtent,
				TEXT("M2_016_Floor")) == nullptr)
			{
				Test.AddError(TEXT("the floor failed to spawn"));
				return false;
			}
			// A hand-built world never runs the map-load collision tree pass;
			// build it once before the first tick (the M1-041 pattern).
			World->EnsureCollisionTreeIsBuilt();

			// The HUD spawns like the game mode spawns it; its BeginPlay binds
			// the session's OnRunEnded (the M2-012 result-screen path).
			FActorSpawnParameters HudParams;
			Hud = World->SpawnActor<APrototypeHUD>(APrototypeHUD::StaticClass(),
				FVector::ZeroVector, FRotator::ZeroRotator, HudParams);
			if (!Test.TestNotNull(TEXT("the prototype HUD spawns in the test world"), Hud))
			{
				return false;
			}

			// The production trigger at its production default location; the
			// suite changes none of its defaults (the wiring under test reads
			// exactly the values the real map's trigger carries).
			FActorSpawnParameters TriggerParams;
			Trigger = World->SpawnActor<ARoomTrigger>(
				ARoomTrigger::StaticClass(), M2_016_TriggerLocation, FRotator::ZeroRotator, TriggerParams);
			if (!Test.TestNotNull(TEXT("the room trigger spawns"), Trigger)
				|| !Test.TestNotNull(TEXT("the trigger carries an activation volume"), Trigger->GetActivationVolume()))
			{
				return false;
			}
			if (!Test.TestTrue(TEXT("the trigger session resolves through the world"),
				Trigger->GetSession() == Session))
			{
				return false;
			}

			Player = M2_016_SpawnPlayer(*World, M2_016_PlayerOutside);
			if (!Test.TestNotNull(TEXT("the real prototype character spawns"), Player))
			{
				return false;
			}
			Player->PlayerDied.AddLambda([this]()
			{
				++PlayerDiedCount;
			});
			return true;
		}

		/** Ticks the world once; the ONLY time source of this suite. */
		bool TickSeconds(FAutomationTestBase& Test, float DeltaSeconds)
		{
			return Test.TestTrue(TEXT("the test world ticks"), Wrapper.TickTestWorld(DeltaSeconds));
		}

		/**
		 * Advances the world by real 60 fps ticks and samples the spawn book
		 * after every tick. No SetSessionClockSeconds call exists anywhere in
		 * this suite - the session clock moves only through the production
		 * character-tick injection.
		 */
		bool AdvanceSeconds(FAutomationTestBase& Test, double Seconds)
		{
			const double StepSeconds = static_cast<double>(M2_016_FrameSeconds);
			double Remaining = Seconds;
			while (Remaining > 1e-9)
			{
				const double StepNow = FMath::Min(StepSeconds, Remaining);
				if (!TickSeconds(Test, M2_016_FrameSeconds))
				{
					return false;
				}
				Remaining -= StepNow;
				SampleSpawns();
			}
			return true;
		}

		/** Records the world-clock time of every newly seen melee enemy. */
		void SampleSpawns()
		{
			if (World == nullptr)
			{
				return;
			}
			int32 Seen = 0;
			for (TActorIterator<AMeleeEnemy> It(World); It; ++It)
			{
				(void)*It;
				++Seen;
			}
			while (EnemySpawnTimes.Num() < Seen)
			{
				EnemySpawnTimes.Add(World->GetTimeSeconds());
			}
		}

		/** Teleports the player and ticks so the overlap state settles, then refreshes the volume query. */
		bool MoveAndTick(FAutomationTestBase& Test, const FVector& Location)
		{
			Player->SetActorLocation(Location, /*bSweep*/ false);
			if (!TickSeconds(Test, M2_016_FrameSeconds) || !TickSeconds(Test, M2_016_FrameSeconds))
			{
				return false;
			}
			Player->GetCapsuleComponent()->UpdateOverlaps();
			SampleSpawns();
			return true;
		}

		/** Alive melee enemies (corpses deliberately not counted). */
		int32 AliveEnemies() const
		{
			int32 Count = 0;
			for (TActorIterator<AMeleeEnemy> It(World); It; ++It)
			{
				UHealthComponent* Health = It->GetHealthComponent();
				if (Health != nullptr && Health->IsAlive())
				{
					++Count;
				}
			}
			return Count;
		}

		/** Every melee enemy actor in the world including corpses. */
		int32 TotalEnemies() const
		{
			int32 Count = 0;
			for (TActorIterator<AMeleeEnemy> It(World); It; ++It)
			{
				++Count;
			}
			return Count;
		}

		/**
		 * Kills every alive melee enemy through the legal lethal path (the
		 * health component's ApplyDamage; the death flows through the spawner
		 * death binding into the session bookkeeping) and registers each as
		 * processed.
		 */
		bool KillAllAliveEnemies(FAutomationTestBase& Test)
		{
			TArray<AMeleeEnemy*> Targets;
			for (TActorIterator<AMeleeEnemy> It(World); It; ++It)
			{
				AMeleeEnemy* Enemy = *It;
				UHealthComponent* Health = (Enemy != nullptr) ? Enemy->GetHealthComponent() : nullptr;
				if (Health != nullptr && Health->IsAlive())
				{
					Targets.Add(Enemy);
				}
			}
			for (AMeleeEnemy* Enemy : Targets)
			{
				if (!Test.TestTrue(
					FString::Printf(TEXT("the enemy %s accepts the lethal damage"), *Enemy->GetName()),
					Enemy->GetHealthComponent()->ApplyDamage(9999.0f) > 0.0f))
				{
					return false;
				}
				KilledEnemies.Add(Enemy);
			}
			return true;
		}

		/** True when every enemy seen so far was born at or near a configured wave location. */
		bool AllBirthsNearConfiguredLocations(FString& OutDetail) const
		{
			int32 Index = 0;
			for (TActorIterator<AMeleeEnemy> It(World); It; ++It)
			{
				AMeleeEnemy* Enemy = *It;
				double BestDistSquared = TNumericLimits<double>::Max();
				for (const FVector& Location : M2_016_Wave0Locations)
				{
					BestDistSquared = FMath::Min(BestDistSquared,
						FVector::DistSquared(Enemy->GetActorLocation(), Location));
				}
				for (const FVector& Location : M2_016_Wave1Locations)
				{
					BestDistSquared = FMath::Min(BestDistSquared,
						FVector::DistSquared(Enemy->GetActorLocation(), Location));
				}
				if (BestDistSquared > M2_016_BirthLocationBandCm * M2_016_BirthLocationBandCm)
				{
					OutDetail = FString::Printf(TEXT("enemy #%d (%s) at %s is outside every configured spawn band"),
						Index + 1, *Enemy->GetName(), *Enemy->GetActorLocation().ToString());
					return false;
				}
				++Index;
			}
			return true;
		}
	};

	// Diagnostics for a failed spawn count: what the session and the world hold.
	static void M2_016_DumpSpawnState(FAutomationTestBase& Test, const FM2_016_Scene& Scene)
	{
		Test.AddInfo(FString::Printf(TEXT("session state=%d spawned=%d killed=%d wave=%d clock=%.3f"),
			static_cast<int32>(Scene.Session->GetState()),
			Scene.Session->GetSpawnedEnemyCount(),
			Scene.Session->GetKilledCount(),
			Scene.Session->GetCurrentWaveIndex(),
			Scene.Session->GetSessionClockSeconds()));
		Test.AddInfo(FString::Printf(TEXT("world melee actors=%d (alive %d), seen spawn events=%d"),
			Scene.TotalEnemies(), Scene.AliveEnemies(), Scene.EnemySpawnTimes.Num()));
	}

