// M2-016: the session production wiring, verified IN THE LOOP. The audit
// before this card found the production session calls only inside the
// PrototypeHUD debug exec: the game main loop never injected the session
// clock (the M2-008 wave pump never ran), RoomTrigger only StartRoom-ed
// without BeginWaves (entering the room spawned nothing), no enemy
// definition runtime asset existed, and RetryRoom/SetPlayer had no
// production caller (the HUD retry button refused for lack of context).
//
// This suite reproduces exactly that hole first (red) and then locks the
// wired production chain (green). The defining property of the suite: it
// NEVER injects a test clock. The session clock comes exclusively from the
// production wiring under test - APrototypeCharacter::Tick handing
// World->GetTimeSeconds() to URoomSessionSubsystem::SetSessionClockSeconds
// (the M1-041 input-clock injection point) - so every birth, the 0.3 s
// spawn slots, the 1.0 s inter-wave wait and the settlement elapse through
// the real game frame pump. The room definition comes from the trigger's
// own production defaults (the Data/rooms.json room_training_01 wave shape:
// 2 + 3 melee_grunt), the enemy definition from the real
// /Game/UEMMO/Enemy/Definitions/DA_melee_grunt asset (generated by
// Scripts/Editor/create_enemy_assets.py from Data/enemies.json), and the
// retry runs through the real HUD HandleRetryRequested path whose context
// the trigger handed over at room entry.
//
// Every kill flows through the legal lethal path only (the health
// component's public ApplyDamage, whose OnDied reaches the spawner death
// binding and from there the session bookkeeping). Scaffolding reuses the
// engine FTestWorldWrapper precedent (GameCombatWiringTests/RoomScenarioTests)
// with uniquely prefixed M2_016 symbols.
